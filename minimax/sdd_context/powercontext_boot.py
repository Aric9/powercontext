"""Start, stop and configure the local PowerContext server.

The module deliberately keeps PowerContext as an external HTTP service: the
context module talks to it through its public REST API, exactly like an agent
host would.  The server uses SQLite, so a clean checkout only needs one command.
"""

from __future__ import annotations

import os
import subprocess
import sys
import time
from pathlib import Path

import httpx

from sdd_context.config import Settings

ENV_FILE = "powercontext.env"
LOG_FILE = "powercontext.log"
PID_FILE = "powercontext.pid"


def _exe() -> str:
    candidate = Path(sys.executable).with_name("powercontext")
    if candidate.exists():
        return str(candidate)
    return "powercontext"


def env_path(settings: Settings) -> Path:
    return settings.data_dir / ENV_FILE


def write_env(settings: Settings) -> Path:
    """Write a deterministic, non-interactive server environment file."""

    settings.data_dir.mkdir(parents=True, exist_ok=True)
    settings.powercontext_home.mkdir(parents=True, exist_ok=True)
    database = settings.data_dir / "powercontext.db"
    lines = [
        "# Generated by sdd_context.powercontext_boot; safe to regenerate.",
        f"POWERCONTEXT_HOME={settings.powercontext_home}",
        "POWERCONTEXT_SERVER_HTTP_HOST=127.0.0.1",
        f"POWERCONTEXT_SERVER_HTTP_PORT={_port(settings)}",
        "POWERCONTEXT_SERVER_ACCESS_MODE=disabled",
        "POWERCONTEXT_SERVER_DASHBOARD_ENABLED=false",
        "POWERCONTEXT_SERVER_MCP_ENABLED=false",
        "POWERCONTEXT_SERVER_DATABASE_KIND=sqlite",
        f"POWERCONTEXT_SERVER_DATABASE_URL=sqlite+aiosqlite:///{database.as_posix()}",
        "POWERCONTEXT_SERVER_LOGGING_LEVEL=INFO",
        "POWERCONTEXT_SERVER_LOGGING_FORMAT=console",
        "POWERCONTEXT_SERVER_LOGGING_ACCESS=true",
        "POWERCONTEXT_SERVER_METRICS_ENABLED=false",
        "POWERCONTEXT_SERVER_TRACING_ENABLED=false",
        "POWERCONTEXT_SERVER_RUNTIME_ARTIFACT_PROCESSING_ROLE=all",
        "POWERCONTEXT_SERVER_RUNTIME_DREAM_ENABLED=false",
        "POWERCONTEXT_SERVER_HANDOFF_REPORT_ENABLED=false",
        "POWERCONTEXT_CLIENT_SERVER_URL=" + settings.powercontext_url,
    ]
    path = env_path(settings)
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return path


def _port(settings: Settings) -> int:
    return int(settings.powercontext_url.rsplit(":", 1)[-1].rstrip("/"))


def health(settings: Settings, timeout: float = 2.0) -> bool:
    try:
        response = httpx.get(settings.powercontext_url + "/health/live", timeout=timeout)
        return response.status_code == 200
    except Exception:
        return False


def start(settings: Settings, wait_seconds: int = 90) -> dict[str, object]:
    """Start the server if it is not already healthy."""

    if health(settings):
        return {"started": False, "already_running": True, "url": settings.powercontext_url}
    settings.data_dir.mkdir(parents=True, exist_ok=True)
    env_file = write_env(settings)
    log = (settings.data_dir / LOG_FILE).open("ab")
    process = subprocess.Popen(
        [_exe(), "server", "run", "--env-file", str(env_file)],
        cwd=str(settings.root),
        stdout=log,
        stderr=subprocess.STDOUT,
        stdin=subprocess.DEVNULL,
        start_new_session=True,
        env={**os.environ, "PYTHONUNBUFFERED": "1"},
    )
    (settings.data_dir / PID_FILE).write_text(str(process.pid), encoding="utf-8")
    deadline = time.time() + wait_seconds
    while time.time() < deadline:
        if health(settings):
            return {"started": True, "pid": process.pid, "url": settings.powercontext_url}
        if process.poll() is not None:
            tail = (settings.data_dir / LOG_FILE).read_text(encoding="utf-8", errors="replace")[-2000:]
            raise RuntimeError(f"PowerContext server exited with {process.returncode}:\n{tail}")
        time.sleep(0.5)
    raise TimeoutError(f"PowerContext server did not become healthy in {wait_seconds}s")


def stop(settings: Settings, wait_seconds: int = 30) -> bool:
    pid_file = settings.data_dir / PID_FILE
    if not pid_file.exists():
        return False
    try:
        pid = int(pid_file.read_text(encoding="utf-8").strip())
    except ValueError:
        pid_file.unlink(missing_ok=True)
        return False
    try:
        os.killpg(os.getpgid(pid), 15)
    except ProcessLookupError:
        pass
    except Exception:
        try:
            os.kill(pid, 15)
        except ProcessLookupError:
            pass
    pid_file.unlink(missing_ok=True)
    deadline = time.time() + wait_seconds
    while time.time() < deadline:
        if not health(settings, timeout=0.5) and not _pid_alive(pid):
            return True
        time.sleep(0.3)
    return True


def _pid_alive(pid: int) -> bool:
    try:
        os.kill(pid, 0)
    except OSError:
        return False
    return True
